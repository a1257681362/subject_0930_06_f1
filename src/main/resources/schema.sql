-- H2 本地文件数据库初始化脚本。
-- 风电叶片巡检台账：风机档案 / 叶片档案 / 换件关系 / 巡检工单 / 无人机影像 / 缺陷 / 维修 / 验收

CREATE TABLE IF NOT EXISTS t_evops_schema_version (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version_no VARCHAR(32) NOT NULL,
    description VARCHAR(255) NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_evops_schema_version UNIQUE (version_no)
);

-- 风机档案：编号唯一，记录场址、机型、并网时间
CREATE TABLE IF NOT EXISTS t_wt_turbine (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    turbine_code VARCHAR(64) NOT NULL,
    site_name VARCHAR(128) NOT NULL,
    model VARCHAR(64) NOT NULL,
    grid_time TIMESTAMP,
    status VARCHAR(16) NOT NULL DEFAULT 'RUNNING',
    remark VARCHAR(255),
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP,
    CONSTRAINT uk_wt_turbine_code UNIQUE (turbine_code)
);

-- 叶片档案：序列号全局唯一；turbine_id 为资产归属（换件也不改），
-- install_time/remove_time 为在役半开区间 [install_time, remove_time)，
-- remove_time 为 NULL 表示至今。换件时刻 T：旧叶止于 T、新叶始于 T，同一时刻不重叠。
CREATE TABLE IF NOT EXISTS t_wt_blade (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    blade_code VARCHAR(64) NOT NULL,
    turbine_id BIGINT NOT NULL,
    position VARCHAR(8) NOT NULL,
    material VARCHAR(64) NOT NULL,
    install_time TIMESTAMP NOT NULL,
    remove_time TIMESTAMP,
    status VARCHAR(16) NOT NULL DEFAULT 'INSTALLED',
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP,
    CONSTRAINT uk_wt_blade_code UNIQUE (blade_code)
);
CREATE INDEX IF NOT EXISTS idx_wt_blade_turbine ON t_wt_blade (turbine_id);

-- 换件记录：保留新旧叶片前后关系
CREATE TABLE IF NOT EXISTS t_wt_blade_replacement (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    turbine_id BIGINT NOT NULL,
    position VARCHAR(8) NOT NULL,
    old_blade_id BIGINT NOT NULL,
    new_blade_id BIGINT NOT NULL,
    replace_time TIMESTAMP NOT NULL,
    reason VARCHAR(255),
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_wt_repl_turbine ON t_wt_blade_replacement (turbine_id);

-- 巡检工单
CREATE TABLE IF NOT EXISTS t_wt_inspection (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_no VARCHAR(64) NOT NULL,
    turbine_id BIGINT NOT NULL,
    blade_id BIGINT,
    inspect_time TIMESTAMP NOT NULL,
    inspector VARCHAR(64) NOT NULL,
    status VARCHAR(16) NOT NULL DEFAULT 'PENDING',
    remark VARCHAR(255),
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP,
    CONSTRAINT uk_wt_inspection_no UNIQUE (order_no)
);

-- 无人机影像
CREATE TABLE IF NOT EXISTS t_wt_drone_image (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    inspection_id BIGINT NOT NULL,
    image_url VARCHAR(512) NOT NULL,
    shoot_time TIMESTAMP,
    location_desc VARCHAR(255),
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_wt_image_inspection ON t_wt_drone_image (inspection_id);

-- 缺陷登记：等级 LOW/MEDIUM/HIGH/CRITICAL；状态机 REGISTERED -> REPAIRED -> ACCEPTED，验收驳回 REJECTED 可重新维修
CREATE TABLE IF NOT EXISTS t_wt_defect (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    defect_no VARCHAR(64) NOT NULL,
    inspection_id BIGINT NOT NULL,
    blade_id BIGINT NOT NULL,
    image_id BIGINT,
    severity VARCHAR(16) NOT NULL,
    description VARCHAR(512),
    status VARCHAR(16) NOT NULL DEFAULT 'REGISTERED',
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP,
    CONSTRAINT uk_wt_defect_no UNIQUE (defect_no)
);
CREATE INDEX IF NOT EXISTS idx_wt_defect_inspection ON t_wt_defect (inspection_id);

-- 维修结果
CREATE TABLE IF NOT EXISTS t_wt_repair (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    defect_id BIGINT NOT NULL,
    repair_time TIMESTAMP NOT NULL,
    repairer VARCHAR(64) NOT NULL,
    repair_result VARCHAR(512),
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_wt_repair_defect ON t_wt_repair (defect_id);

-- 验收结论
CREATE TABLE IF NOT EXISTS t_wt_acceptance (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    defect_id BIGINT NOT NULL,
    accept_time TIMESTAMP NOT NULL,
    acceptor VARCHAR(64) NOT NULL,
    result VARCHAR(8) NOT NULL,
    comment VARCHAR(512),
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_wt_accept_defect ON t_wt_acceptance (defect_id);

MERGE INTO t_evops_schema_version (version_no, description)
KEY (version_no)
VALUES ('base-0', 'EVOPS 初始工作区');

MERGE INTO t_evops_schema_version (version_no, description)
KEY (version_no)
VALUES ('wt-1', '风电叶片巡检台账：风机/叶片/换件/巡检/影像/缺陷/维修/验收');
